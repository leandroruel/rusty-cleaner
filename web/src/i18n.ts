let currentLocale: Locale = "en";

export function getLocale(): Locale {
  return currentLocale;
}

export function setLocale(locale: Locale): void {
  currentLocale = locale;
  localStorage.setItem("rusty-cleaner-locale", locale);
  document.documentElement.lang = locale;
}

export function loadLocale(): Locale {
  const saved = localStorage.getItem("rusty-cleaner-locale");
  const locale: Locale = saved === "pt-BR" ? "pt-BR" : "en";
  setLocale(locale);
  return locale;
}

export function t(key: string, vars: Record<string, string | number> = {}): string {
  const template = dictionaries[currentLocale][key] ?? dictionaries.en[key] ?? key;
  return Object.entries(vars).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

export function number(value: number): string {
  return value.toLocaleString(currentLocale);
}
